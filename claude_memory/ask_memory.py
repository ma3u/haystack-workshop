"""
Ask the agent-memory graph the ten questions in cypher/questions.cypher and document the answers.

Writes, for every question:
  results/memory_questions.md         question, Cypher, result table
  results/screenshots/qNN.png         terminal-style screenshot of the result table

Run:  uv run --no-project --with neo4j --with pillow python claude_memory/ask_memory.py --uri bolt://127.0.0.1:7689
Only reads the graph. The password comes from the workshop .env (NEO4J_PASSWORD).
"""
import argparse
import re
from pathlib import Path

from neo4j import GraphDatabase

HERE = Path(__file__).resolve().parent
QUESTIONS = HERE / "cypher" / "questions.cypher"
OUT = HERE / "results"
SHOTS = OUT / "screenshots"
ENV = HERE.parent / ".env"
MAX_CELL = 110


def load_questions() -> list[tuple[str, str, str]]:
    """Split questions.cypher on '// Qn: title' headers -> [(id, title, cypher)]."""
    text = QUESTIONS.read_text()
    parts = re.split(r"^// (Q\d+): (.*)$", text, flags=re.M)
    return [(parts[i], parts[i + 1].strip(), parts[i + 2].strip().rstrip(";")) for i in range(1, len(parts), 3)]


def cell(value) -> str:
    if isinstance(value, list):
        value = ", ".join(map(str, value))
    text = "" if value is None else str(value)
    text = re.sub(r"\s+", " ", text)
    return text if len(text) <= MAX_CELL else text[: MAX_CELL - 1] + "…"


def table(keys: list[str], rows: list[list[str]]) -> str:
    widths = [max(len(k), *(len(r[i]) for r in rows)) if rows else len(k) for i, k in enumerate(keys)]
    line = lambda vals: "│ " + " │ ".join(v.ljust(w) for v, w in zip(vals, widths)) + " │"
    sep = lambda l, m, r: l + m.join("─" * (w + 2) for w in widths) + r
    out = [sep("┌", "┬", "┐"), line(keys), sep("├", "┼", "┤")] + [line(r) for r in rows] + [sep("└", "┴", "┘")]
    return "\n".join(out)


def screenshot(path: Path, title: str, body: str) -> None:
    """Render the result like a dark terminal window (what you see when running the query in a shell)."""
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype("/System/Library/Fonts/Menlo.ttc", 15)
    bold = ImageFont.truetype("/System/Library/Fonts/Menlo.ttc", 16, index=1)
    lines = body.splitlines()
    cw, lh, pad, bar = font.getlength("M"), 21, 24, 34
    width = int(max(font.getlength(l) for l in lines + [title]) + 2 * pad)
    height = bar + pad + lh * (len(lines) + 2) + pad
    img = Image.new("RGB", (max(width, 640), height), "#1e1e2e")
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, img.width, bar], fill="#313244")
    for i, c in enumerate(["#f38ba8", "#f9e2af", "#a6e3a1"]):
        d.ellipse([14 + i * 22, 11, 26 + i * 22, 23], fill=c)
    d.text((90, 8), "agent memory · neo4j://127.0.0.1 · read-only", font=font, fill="#a6adc8")
    d.text((pad, bar + pad), title, font=bold, fill="#89b4fa")
    for i, l in enumerate(lines):
        d.text((pad, bar + pad + lh * (i + 2)), l, font=font, fill="#cdd6f4" if i > 2 else "#f9e2af")
    img.save(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--uri", default="bolt://127.0.0.1:7689")
    args = parser.parse_args()
    env = dict(re.findall(r"^([A-Z0-9_]+)=(.*)$", ENV.read_text(), re.M))
    SHOTS.mkdir(parents=True, exist_ok=True)

    md = ["# Agent memory: 10 questions about Neo4j projects and challenges", "",
          f"Graph: `{args.uri}` (meta-knowledge-graph schema, imported Claude Code history). Generated by `ask_memory.py`.", ""]
    with GraphDatabase.driver(args.uri, auth=(env.get("NEO4J_USERNAME", "neo4j").strip(), env["NEO4J_PASSWORD"].strip())) as d:
        for qid, title, cypher in load_questions():
            records, _, _ = d.execute_query(cypher, routing_="r")
            keys = list(records[0].keys()) if records else ["(no rows)"]
            rows = [[cell(r[k]) for k in keys] for r in records]
            out = table(keys, rows)
            print(f"\n{qid}: {title}\n{out}")
            shot = SHOTS / f"{qid.lower()}.png"
            screenshot(shot, f"{qid}: {title}", out)
            md += [f"## {qid}: {title}", "", "```cypher", cypher, "```", "",
                   f"![{qid} result](screenshots/{shot.name})", "", "<details><summary>Result as text</summary>", "",
                   "```text", out, "```", "", "</details>", ""]
    (OUT / "memory_questions.md").write_text("\n".join(md))
    print(f"\nwrote {OUT / 'memory_questions.md'} and {len(list(SHOTS.glob('q*.png')))} screenshots")


if __name__ == "__main__":
    main()
